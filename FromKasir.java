    private void btnBayarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBayarActionPerformed
      
    try {
        if (txtTotal.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Silakan hitung total harga terlebih dahulu!");
            return;
        }

        if (txtBayar.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Uang pembayaran harus diisi!");
            return;
        }

        int total = Integer.parseInt(txtTotal.getText());
        int bayar = Integer.parseInt(txtBayar.getText());

        if (bayar < 0) {
            JOptionPane.showMessageDialog(this,
                    "Pembayaran tidak boleh negatif!");
            return;
        }

        if (bayar < total) {
            JOptionPane.showMessageDialog(this,
                    "Pembayaran kurang Rp" + (total - bayar));
            txtKembalian.setText("");
            return;
        }

        int kembalian = bayar - total;

        txtKembalian.setText(String.valueOf(kembalian));

        JOptionPane.showMessageDialog(this,
                "Pembayaran berhasil!\nUang kembalian: Rp"
                + kembalian);

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Uang pembayaran harus berupa angka!");
    }

    }//GEN-LAST:event_btnBayarActionPerformed

    private void btnHitungActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHitungActionPerformed

    try {
        if (txtNama.getText().trim().isEmpty()
                || txtHarga.getText().trim().isEmpty()
                || txtJumlah.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(null,
                    "Semua data harus diisi!");

            return;
        }

        int harga = Integer.parseInt(txtHarga.getText());
        int jumlah = Integer.parseInt(txtJumlah.getText());

        if (harga < 0 || jumlah <= 0) {
            JOptionPane.showMessageDialog(null,
                    "Harga tidak boleh negatif dan jumlah harus lebih dari 0!");
            return;
        }

        int total = harga * jumlah;

        txtTotal.setText(String.valueOf(total));
        txtKembalian.setText("");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(null,
                "Harga dan jumlah harus berupa angka!");
    }
    }//GEN-LAST:event_btnHitungActionPerformed

